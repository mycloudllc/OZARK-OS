#!/usr/bin/env bash
# Regenerate meta-ozark/conf/distro/include/ozark-rpi-overlays.inc: the full
# set of device tree overlays the Raspberry Pi kernel builds, the same set
# Raspberry Pi OS ships in /boot/overlays.
#
#   ./scripts/gen-rpi-overlays.sh [kernel-version]
#
# kernel-version picks meta-raspberrypi's linux-raspberrypi_<version>.bb
# (default 6.6, meta-raspberrypi's default for Scarthgap). Rerun after a
# layer update or a kernel version change; overlays come and go between
# kernel releases, and the kernel build fails on any it doesn't know.
#
# Needs a fetched kernel (the git mirror under cache/downloads), i.e. one
# build or `bitbake -c fetch linux-raspberrypi` first.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
version="${1:-6.6}"
recipe="$ROOT/build/meta-raspberrypi/recipes-kernel/linux/linux-raspberrypi_${version}.bb"
mirror="${OZARK_DL_DIR:-$ROOT/cache/downloads}/git2/github.com.raspberrypi.linux.git"
out="$ROOT/meta-ozark/conf/distro/include/ozark-rpi-overlays.inc"

[ -f "$recipe" ] || { echo "no recipe: $recipe" >&2; exit 1; }
[ -d "$mirror" ] || { echo "no kernel git mirror: $mirror" >&2; exit 1; }

srcrev="$(sed -n 's/^SRCREV_machine = "\(.*\)"/\1/p' "$recipe")"
linux_version="$(sed -n 's/^LINUX_VERSION ?= "\(.*\)"/\1/p' "$recipe")"

overlays="$(git --git-dir="$mirror" show "$srcrev:arch/arm/boot/dts/overlays/Makefile" \
    | grep -oE '^[[:space:]]+[A-Za-z0-9_.,+-]+\.dtbo' | tr -d '[:blank:]' | sort -u)"

mkdir -p "$(dirname "$out")"
{
    echo "# Every device tree overlay the Raspberry Pi kernel builds, so any"
    echo "# dtoverlay=... from the Raspberry Pi docs works in config.txt without a rebuild."
    echo "# meta-raspberrypi only ships a short default list."
    echo "#"
    echo "# GENERATED by scripts/gen-rpi-overlays.sh from linux-raspberrypi ${linux_version}"
    echo "# (${srcrev}). Rerun it when the kernel changes; don't edit by hand."
    echo
    echo "RPI_KERNEL_DEVICETREE_OVERLAYS:rpi = \" \\"
    echo "    overlays/overlay_map.dtb \\"
    while read -r o; do echo "    overlays/$o \\"; done <<<"$overlays"
    echo "    \""
} >"$out"

echo "wrote $(grep -c '\.dtbo' "$out") overlays to ${out#"$ROOT"/}"
